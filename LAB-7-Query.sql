--9. Create trigger to Allow enrolment in month from Jan to August, otherwise print message enrolment closed.
CREATE OR ALTER TRIGGER TR_INSTEAD_OF_ENROLLMENT
ON ENROLLMENT
INSTEAD OF INSERT
AS BEGIN
		DECLARE @MON INT
		SELECT @MON = MONTH(EnrollmentDate) FROM inserted
	IF @MON <= 8
		BEGIN
			INSERT INTO ENROLLMENT SELECT * FROM inserted
		END
	
	ELSE
		BEGIN
			PRINT 'NOT ALLOW'
		END
END


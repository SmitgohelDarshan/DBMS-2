--6. Create trigger for student age validation (Min 18). 
CREATE OR ALTER TRIGGER TR_INSTEAD_OF_STUDENT_AGE_VALIDATION
ON STUDENT
INSTEAD OF INSERT
AS BEGIN
	DECLARE @AGE INT, @DOB DATE
	SELECT @DOB = StuDateOfBirth FROM inserted
	SET @AGE = DATEDIFF(YEAR,@DOB, GETDATE())

	IF @AGE < 18
		BEGIN
			PRINT 'STUDENT AGE VALIDATION(MIN 18)'
		END
	ELSE
		BEGIN
			INSERT INTO STUDENT(StudentID,StuEmail,StuPhone,StuDepartment,StuDateOfBirth,StuEnrollmentYear,CGPA)
			SELECT StudentID,StuEmail,StuPhone,StuDepartment,StuDateOfBirth,StuEnrollmentYear,CGPA FROM inserted
		END
END

DROP TRIGGER TR_INSTEAD_OF_STUDENT_AGE_VALIDATION



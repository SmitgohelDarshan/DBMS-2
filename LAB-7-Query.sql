--10. Create trigger to Allow only grade change in enrollment (block other updates)
CREATE OR ALTER TRIGGER TR_AFTER_ENROLLMENT_UPDATE_GRADE
ON ENROLLMENT
AFTER UPDATE
AS BEGIN
	DECLARE @OLD VARCHAR(10), @NEW VARCHAR(10), @ID INT
	SELECT @OLD = GRADE FROM deleted
	SELECT @NEW = GRADE FROM inserted
	SELECT @ID = EnrollmentID FROM inserted
	IF @OLD != @NEW
		BEGIN
			UPDATE ENROLLMENT
			SET Grade = @NEW
			WHERE EnrollmentID = @ID
		END
	ELSE
		BEGIN
			PRINT 'DO NOT ALLOW TO CHANGE ANOTHER COLOUMN'
		END
END

DROP TRIGGER TR_AFTER_ENROLLMENT_UPDATE_GRADE